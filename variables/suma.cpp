#include <iostream>

using namespace std;

int main()
{

    int a = 10;
    int b = 3;

    cout << "suma: " << a + b << endl;
    cout << "resta: " << a - b << endl;
    cout << "multiplicacion: " << a * b << endl;
    cout << "division: " << a / b << endl;
    cout << "residuo: " << a % b << endl;

    return 0;
}